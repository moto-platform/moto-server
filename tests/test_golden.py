"""Golden C vectors for the rt-core host tests (D-070 item 2): drift check and sanity."""

from __future__ import annotations

import hashlib
import re
import shutil
import subprocess
from pathlib import Path

import pytest

from moto_server.defs import defs_version
from moto_server.derived import golden

MANIFEST = Path(__file__).parent / "golden" / "MANIFEST.sha256"
SCENARIO_HEADERS = [f"derived_{s.name}.h" for s in golden.SCENARIOS]


@pytest.fixture(scope="module")
def generated(tmp_path_factory) -> tuple[golden.Generation, Path]:
    out = tmp_path_factory.mktemp("vectors")
    return golden.write(out, None), out


def test_manifest_matches_regeneration(generated):
    gen, _ = generated
    hint = (
        "the Python reference or the defs pin changed: run "
        "`uv run moto-server golden --out <moto-rt-core>/tests/host/vectors`, commit the "
        "headers in moto-rt-core and tests/golden/MANIFEST.sha256 here"
    )
    assert MANIFEST.read_text() == golden.manifest_text(gen.files), hint


def test_manifest_lists_pinned_defs():
    assert f"defs {defs_version()}\n" in MANIFEST.read_text()


def test_generation_is_deterministic(generated):
    gen, _ = generated
    again = golden.generate()
    assert [f.text for f in again.files] == [f.text for f in gen.files]


def test_banner_hash_covers_the_body(generated):
    gen, out = generated
    for f in gen.files:
        text = (out / f.name).read_text()
        stated, body = golden.split_banner(text)
        assert stated == hashlib.sha256(body.encode()).hexdigest() == f.sha256
        assert defs_version() in text.splitlines()[0]
        assert "GENERATED by moto-server" in text.splitlines()[0]


def test_no_gps_input_is_selected():
    selected = golden.select_signals()
    assert selected
    for name, spec in selected.items():
        assert not any("gps" in i.lower() for i in spec["inputs"]), name
        assert not any(i.startswith("sensor.") for i in spec["inputs"]), name
    for f in golden.generate().files:
        code = re.sub(r"/\*.*?\*/", "", f.text, flags=re.S)  # the comments name the rule
        assert "gps" not in code.lower()


def test_every_selected_signal_is_valid_somewhere(generated):
    gen, _ = generated
    assert gen.selected
    for signal, per in gen.coverage.items():
        assert sum(per.values()) > 0, signal


def test_flags_in_outputs_are_in_the_enum(generated):
    _, out = generated
    types = (out / golden.TYPES_HEADER).read_text()
    enum = set(re.findall(r"(DERIVED_VECTOR_FLAG_\w+) = \d+", types))
    assert enum == {"DERIVED_VECTOR_FLAG_NONE", *map(golden.flag_constant, golden.FLAG_ORDER)}
    for name in SCENARIO_HEADERS:
        used = set(re.findall(r"DERIVED_VECTOR_FLAG_\w+", (out / name).read_text()))
        assert used <= enum, name


def test_flag_order_covers_the_reference_flags():
    assert golden.used_flags() == set(golden.FLAG_ORDER)


def test_count_macros_match_the_arrays(generated):
    _, out = generated
    for scenario in golden.SCENARIOS:
        n, upper = scenario.name, scenario.name.upper()
        text = (out / f"derived_{n}.h").read_text()
        for kind, array in (("INPUT", "inputs"), ("OUTPUT", "outputs"), ("TOL", "tol")):
            count = int(re.search(rf"DERIVED_{upper}_{kind}_COUNT \((\d+)u\)", text)[1])
            block = re.search(rf"derived_{n}_{array}\[\] = \{{\n(.*?)\n\}};", text, re.S)[1]
            assert count == len(block.splitlines()) > 0, (n, array)


def test_rows_are_ordered_and_invalid_rows_are_zero(generated):
    _, out = generated
    for scenario in golden.SCENARIOS:
        text = (out / f"derived_{scenario.name}.h").read_text()
        for array in ("inputs", "outputs"):
            block = re.search(
                rf"derived_{scenario.name}_{array}\[\] = \{{\n(.*?)\n\}};", text, re.S
            )
            times = [int(m) for m in re.findall(r"\{ (\d+)u,", block[1])]
            assert times == sorted(times)
        assert not re.search(r"false, DERIVED_VECTOR_FLAG_\w+, (?!0\.0f)", text)
        assert "false, DERIVED_VECTOR_FLAG_NONE" not in text
        assert not re.search(r"\b(inf|nan)\b", text, re.I)


def test_float_literals():
    assert golden.c_float(1.0) == "1.0f"
    assert golden.c_float(-0.0) == "0.0f"
    assert golden.c_float(0.1) == "0.100000001f"
    assert golden.c_float(1e-5).endswith("f")
    with pytest.raises(ValueError):
        golden.c_float(float("inf"))
    with pytest.raises(ValueError):
        golden.c_float(float("nan"))


@pytest.mark.skipif(shutil.which("cc") is None, reason="no C compiler")
def test_headers_compile_as_c99(generated, tmp_path):
    _, out = generated
    lines = [f'#include "{name}"' for name in SCENARIO_HEADERS]
    lines.append(f'#include "{golden.TYPES_HEADER}"')
    for s in golden.SCENARIOS:
        n, u = s.name, s.name.upper()
        for kind, array in (("INPUT", "inputs"), ("OUTPUT", "outputs"), ("TOL", "tol")):
            lines.append(
                f"typedef char check_{n}_{array}"
                f"[(sizeof(derived_{n}_{array}) / sizeof(derived_{n}_{array}[0]) "
                f"== DERIVED_{u}_{kind}_COUNT) ? 1 : -1];"
            )
    lines.append(
        f"int main(void) {{ return derived_{golden.SCENARIOS[0].name}_tol[0].signal > 1000u; }}"
    )
    source = tmp_path / "check.c"
    source.write_text("\n".join(lines) + "\n")
    result = subprocess.run(
        [
            "cc", "-std=c99", "-pedantic", "-Wall", "-Wextra", "-Werror",
            "-I", str(golden.DEFS_C_RT_CORE), "-I", str(out),
            "-c", str(source), "-o", str(tmp_path / "check.o"),
        ],
        capture_output=True,
        text=True,
    )  # fmt: skip
    assert result.returncode == 0, result.stderr
